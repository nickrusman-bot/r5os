# Regenerates distro/app_server/compositor/compositor_shaders.h from the
# GLSL next to it. Run in WSL. The header is never edited by hand.
# glslang is a host build tool, built from the 16.6.0 source tag
# (sha256 9c09b901149c729df745057dafa815278aaa101b84d2b6e14f16a42de52f97f2)
# into /home/nickr/r5os/mesa-build/glslang-16.6.0; nothing of it ships.
set -euo pipefail

GLSLANG="${GLSLANG:-/home/nickr/r5os/mesa-build/glslang-16.6.0/bin/glslang}"
DIR="$(cd "$(dirname "$0")/../distro/app_server/compositor" && pwd)"
OUT="$DIR/compositor_shaders.h"
TMP="$(mktemp)"
TMP_EFFECTS="$(mktemp)"
trap 'rm -f "$TMP" "$TMP_EFFECTS"' EXIT

"$GLSLANG" --version | head -1
"$GLSLANG" -V --target-env vulkan1.1 --vn kComposeSpirv -o "$TMP" \
	"$DIR/compose.comp"
# M11 step 4 (decision 16): the effects pipeline
"$GLSLANG" -V --target-env vulkan1.1 --vn kEffectsSpirv -o "$TMP_EFFECTS" \
	"$DIR/effects.comp"

{
	printf '%s\n' \
		'/*' \
		' * SPDX-FileCopyrightText: 2026 R5OS Contributors' \
		' * SPDX-License-Identifier: MIT' \
		' *' \
		' * Generated by scripts/gen-compositor-shaders.sh from compose.comp' \
		' * and effects.comp' \
		' * with glslang 16.6.0. Do not edit by hand.' \
		' */'
	tr -d '\r' < "$TMP"
	tr -d '\r' < "$TMP_EFFECTS"
} > "$OUT"
echo "wrote $OUT"
